-- ---- 執行時套用（zhTW_Names_runtime.lua，由 zhnames.py 接在名稱表後面） ----
-- 插件拿地區、副本、首領名跟遊戲（中文用戶端）比對，換成遊戲的中文名反而對得上；首領擊殺依 encounter ID 記錄，不受影響。

-- 地城、團隊副本
for _, list in ipairs({ ns.DUNGEONS or {}, ns.RAIDS or {} }) do
  for _, d in ipairs(list) do d[2] = N.dungeon[d[1]] or d[2] end
end
-- 副本、首領、地城搜尋器（每個遊戲版本）
for _, E in pairs(ns.ENCOUNTERS or {}) do
  if type(E) == "table" then
    for id, name in pairs(E.finder or {}) do E.finder[id] = N.finder[id] or name end
    for inst, m in pairs(E.maps or {}) do
      m[1] = N.instance[inst] or m[1]
      for i = 2, #m do
        if type(m[i]) == "table" then m[i][2] = N.boss[m[i][1]] or m[i][2] end
      end
    end
  end
end
-- 共用副本的分翼首領名、選用首領：保留英文再加上中文（比對時兩種都認得）
for _, m in pairs(ns.DUNGEON_MAPS or {}) do
  for i = 2, #m do
    local zh = N.bossEN[m[i]]
    if zh then m[#m + 1] = zh end
  end
end
if ns.OPTIONAL_BOSSES then
  local add = {}
  for en in pairs(ns.OPTIONAL_BOSSES) do if N.bossEN[en] then add[N.bossEN[en]] = true end end
  for zh in pairs(add) do ns.OPTIONAL_BOSSES[zh] = true end
end
-- 調諧、鑰匙
for _, a in ipairs(ns.ATTUNEMENTS or {}) do a.name = N.att[a.name] or a.name end

-- 任務起點、地城入口：地區換中文；NPC 名字先記下英文原名，學到中文就換
local byIndex, startOf = {}, {}
local seen = {}
local function walk(t, id)
  if type(t) ~= "table" or seen[t] then return end
  seen[t] = true
  if type(t.zone) == "string" then t.zone = N.zone[t.zone] or t.zone end
  if type(t.by) == "string" then
    t.byEN = t.byEN or t.by
    local list = byIndex[t.byEN] or {}
    byIndex[t.byEN] = list
    list[#list + 1] = t
    t.by = N.npc[t.byEN] or t.by
    if id then startOf[id] = t end
  end
  for k, v in pairs(t) do
    if type(v) == "table" then
      -- QUEST_STARTS[id] = {...}；步驟 { id, name, by = ... }
      walk(v, (t == ns.QUEST_STARTS and k) or (type(v[1]) == "number" and v[1]) or nil)
    end
  end
end
walk(ns.QUEST_STARTS)
walk(ns.DUNGEON_ENTRANCES)
walk(ns.ATTUNEMENTS)

local function setNPC(en, zh)
  for _, t in ipairs(byIndex[en] or {}) do t.by = zh end
end

local f = CreateFrame("Frame")
f:RegisterEvent("ADDON_LOADED")
f:RegisterEvent("QUEST_DETAIL")
f:SetScript("OnEvent", function(_, event, arg)
  if event == "ADDON_LOADED" then
    if arg ~= "JourneyTogetherForever" then return end
    JTFzhTWNames = type(JTFzhTWNames) == "table" and JTFzhTWNames or {}
    JTFzhTWNames.npc = type(JTFzhTWNames.npc) == "table" and JTFzhTWNames.npc or {}
    for en, zh in pairs(JTFzhTWNames.npc) do
      if type(en) == "string" and type(zh) == "string" then setNPC(en, zh) end
    end
    return
  end
  -- QUEST_DETAIL：打開任務說明時，給任務的 NPC（或物件）就是資料裡的 by
  local id = GetQuestID and GetQuestID()
  local t = id and startOf[id]
  if not (t and t.byEN) then return end
  local name = UnitName and UnitName("npc")
  if type(name) ~= "string" or (issecretvalue and issecretvalue(name)) or name == "" then return end
  if not name:find("[\128-\255]") or name == t.by then return end -- 只記中文名
  JTFzhTWNames = JTFzhTWNames or {}
  JTFzhTWNames.npc = JTFzhTWNames.npc or {}
  JTFzhTWNames.npc[t.byEN] = name
  setNPC(t.byEN, name)
  if ns.Window and ns.Window.RefreshSoon then ns.Window:RefreshSoon("quests") end
end)
